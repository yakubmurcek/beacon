#!/usr/bin/env python3
"""The SQLite schema the old hub creates, captured for the TypeScript reverse-copy tool.

  python3 scripts/sqlite_ddl.py           # rewrite ts/packages/db/src/sqlite-ddl.ts from the hub's own code
  python3 scripts/sqlite_ddl.py --check   # exit 1 when the hub now creates a different schema (tests run this)

The hub's modules create and alter their tables on start. This starts the hub on a throwaway file (HUB_LOOPS=0, the
example settings, a port the OS picks), stops it as soon as it serves, and reads every CREATE statement back in the
order SQLite keeps them. The reverse tool applies exactly these, so the file it writes is the one a fresh hub makes.
"""
import json
import os
import sqlite3
import subprocess
import sys
import tempfile
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(ROOT, 'ts', 'packages', 'db', 'src', 'sqlite-ddl.ts')
HEADER = ('// Generated by scripts/sqlite_ddl.py from the old hub\'s own table creation; do not edit by hand.\n'
          '// The CREATE statements a fresh hub runs, in SQLite\'s order: the reverse-copy tool applies them to a new file.\n')


def hub_ddl(timeout=30):
    with tempfile.TemporaryDirectory() as tmp:
        db = os.path.join(tmp, 'usage.db')
        env = {**os.environ, 'USAGE_DB': db, 'USAGE_PORT': '0', 'HUB_LOOPS': '0',
               'BEACON_CONFIG': os.path.join(ROOT, 'config.example.json')}
        for k in ('HUB_ALARMS', 'TASKS_TOKEN', 'USAGE_TOKEN'):
            env.pop(k, None)
        hub = subprocess.Popen([sys.executable, os.path.join(ROOT, 'hub', 'server.py')], env=env,
                               stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        try:
            deadline = time.time() + timeout
            for line in hub.stdout or ():  # the line it logs right before it serves: every table exists by then
                if 'agent usage hub on' in line:
                    break
                if time.time() > deadline:
                    raise RuntimeError('the hub did not start in time')
            else:
                raise RuntimeError('the hub exited before it served')
        finally:
            hub.terminate()
            hub.wait(10)
        con = sqlite3.connect(db)
        try:
            return [sql for (sql,) in con.execute(
                "SELECT sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid")]
        finally:
            con.close()


def render(statements):
    body = ',\n'.join('  ' + json.dumps(s, ensure_ascii=False) for s in statements)
    return HEADER + f'export const SQLITE_DDL: readonly string[] = [\n{body},\n];\n'


def main(argv):
    text = render(hub_ddl())
    if '--check' in argv:
        with open(TARGET, encoding='utf-8') as f:
            if f.read() != text:
                print(f'{os.path.relpath(TARGET, ROOT)} is out of date: run python3 scripts/sqlite_ddl.py')
                return 1
        return 0
    with open(TARGET, 'w', encoding='utf-8') as f:
        f.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
